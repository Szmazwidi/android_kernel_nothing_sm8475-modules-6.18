"""Regenerate kernel/module/pong251-module-policy.h from a set of built modules.

The 6.18.32 and 6.18.59 kernel branches carry a lab guard ("pong: LAB: Load only the
verified module payloads") that refuses any module whose ELF payload is not listed
in kernel/module/pong251-module-policy.h. The payload is the .ko file without the
appended PKCS#7 signature, i.e. exactly what load_module() hashes after
module_sig_check() has removed the signature.

When you rebuild the modules, their payloads change (at least .BTF, which depends
on vmlinux), so the list has to be regenerated from the modules you are going to
ship, and the kernel rebuilt with the new header:

    tools/gen-module-policy.py out/pong/frozen/modules > common/kernel/module/pong251-module-policy.h

Use prepare-modules.py freeze first to select the complete vendor/GKI set.
Directories are searched recursively for *.ko. This regenerates only the exact
module payload list; critical device write/identity protections remain unchanged.
"""
import hashlib
import os
import struct
import sys

MAGIC = b'~Module signature appended~\n'
# struct module_signature: algo, hash, id_type, signer_len, key_id_len, pad[3], sig_len (be32)
SIG_STRUCT = struct.Struct('>BBBBB3xI')


def payload(data):
    """Strip an appended module signature the same way module_sig_check() does."""
    if not data.endswith(MAGIC):
        return data
    body = data[:-len(MAGIC)]
    if len(body) < SIG_STRUCT.size:
        raise ValueError('Truncated module signature trailer')
    sig_len = SIG_STRUCT.unpack(body[-SIG_STRUCT.size:])[-1]
    if not sig_len or sig_len > len(body) - SIG_STRUCT.size:
        raise ValueError('Invalid module signature size')
    return body[:-SIG_STRUCT.size - sig_len]


def collect(paths):
    files = []
    for p in paths:
        if os.path.isdir(p):
            for dp, _, fn in os.walk(p):
                files += [os.path.join(dp, f) for f in fn if f.endswith('.ko')]
        else:
            files.append(p)
    return sorted(files, key=os.path.basename)


def main(argv):
    if len(argv) < 2 or argv[1] in ('-h', '--help'):
        sys.stderr.write(__doc__)
        return 2
    seen = {}
    names = {}
    for f in collect(argv[1:]):
        body = payload(open(f, 'rb').read())
        if body[:6] != b'\x7fELF\x02\x01' or len(body) < 64:
            raise ValueError('Not an ELF64 module: ' + f)
        key = (len(body), hashlib.sha256(body).digest())
        name = os.path.basename(f)
        if name in names and names[name] != key:
            raise ValueError('Different payloads share a module filename: ' + name)
        names[name] = key
        seen.setdefault(key, name)
    out = sys.stdout
    out.write('/* SPDX-License-Identifier: GPL-2.0-only */\n'
              '/* Exact module ELF payloads that load_module() accepts (generated by\n'
              ' * tools/gen-module-policy.py of android_kernel_nothing_sm8475-modules-6.18).\n'
              ' * Native module_sig_check authenticates/removes the PKCS#7 trailer first.\n'
              ' * This hash gate then runs before ELF setup, relocation or any module code. */\n'
              '#include <crypto/sha2.h>\n'
              'static const struct { unsigned long bytes; u8 digest[32]; } pong251_modules[] = {\n')
    for (size, digest), name in sorted(seen.items(), key=lambda kv: kv[1]):
        out.write('    {%d, {%s}}, /* %s */\n' % (size, ','.join('0x%02x' % b for b in digest), name))
    out.write('};\n'
              'static bool pong251_module_allowed(const void *data, unsigned long bytes)\n'
              '{\n'
              '    u8 digest[32];\n'
              '    unsigned int i;\n'
              '    bool possible = false;\n'
              '    for (i = 0; i < ARRAY_SIZE(pong251_modules); i++)\n'
              '        if (bytes == pong251_modules[i].bytes)\n'
              '            possible = true;\n'
              '    if (!possible)\n'
              '        return false;\n'
              '    sha256(data, bytes, digest);\n'
              '    for (i = 0; i < ARRAY_SIZE(pong251_modules); i++)\n'
              '        if (bytes == pong251_modules[i].bytes &&\n'
              '            !memcmp(digest, pong251_modules[i].digest, sizeof(digest)))\n'
              '            return true;\n'
              '    return false;\n'
              '}\n')
    sys.stderr.write('%d module payloads\n' % len(seen))
    return 0


if __name__ == '__main__':
    sys.exit(main(sys.argv))
